const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
(async () => {
 const base=(process.env.TEST_BASE_URL || 'http://127.0.0.1:8765').replace(/\/$/, '');
 const output=path.resolve(__dirname, '../qa-output'); fs.mkdirSync(output,{recursive:true});
 const browser=await chromium.launch({...(process.env.PLAYWRIGHT_CHROMIUM_PATH ? {executablePath:process.env.PLAYWRIGHT_CHROMIUM_PATH} : {}),headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const failed=[];page.on('response',r=>{if(r.status()>=400)failed.push(`${r.status()} ${r.url()}`)});
 await page.goto(base,{waitUntil:'networkidle'});
 await page.screenshot({path:path.join(output,'desktop-full.png'),fullPage:true});
 await page.screenshot({path:path.join(output,'desktop-hero.png')});
 const assert=(v,m)=>{if(!v)throw Error(m); console.log('PASS '+m)};
 assert(await page.locator('.project-card').count()===8,'all 8 projects render');
 for(const [id,count] of Object.entries({graphic:2,type:1,poster:2,ui:1,motion:1,ip:1,all:8})){
  await page.locator(`[data-filter="${id}"]`).click();
  assert(await page.locator('.project-card').count()===count,`${id} filter: ${count} result(s)`);
  assert(await page.locator(`[data-filter="${id}"]`).getAttribute('aria-pressed')==='true',`${id} filter selection state`);
 }
 await page.locator('.project-card').first().click();
 assert(await page.locator('#project-dialog').evaluate(el=>el.open),'dialog opens');
 assert(await page.locator('#dialog-title').textContent()==='OFF / GRID','correct project title');
 assert(await page.evaluate(()=>document.activeElement.classList.contains('dialog-close')),'initial dialog focus');
 await page.keyboard.press('Shift+Tab');
 assert(await page.evaluate(()=>document.activeElement.closest('#project-dialog')!==null),'dialog traps backward keyboard focus');
 await page.keyboard.press('Tab');
 await page.keyboard.press('Escape');
 assert(!(await page.locator('#project-dialog').evaluate(el=>el.open)),'Escape closes dialog');
 assert(await page.evaluate(()=>document.activeElement.classList.contains('project-card')),'focus returns to project trigger');
 await page.locator('.project-card').first().click();
 await page.locator('[data-next-project]').click();
 assert(await page.locator('#dialog-title').textContent()==='BETWEEN 字间','next project navigates');
 assert(await page.locator('#project-dialog').evaluate(el=>el.scrollTop===0),'next project resets dialog scroll');
 await page.locator('.dialog-close').click();
 await page.goto(base+'/#project/mimo',{waitUntil:'networkidle'});
 assert(await page.locator('#dialog-title').textContent()==='MIMO','project deep link works');
 await page.mouse.click(5,5);
 assert(!(await page.locator('#project-dialog').evaluate(el=>el.open)),'backdrop click closes');
 await page.locator('[data-project="field"]').click();
 await page.screenshot({path:path.join(output,'desktop-project.png')});
 await page.goBack();
 assert(!(await page.locator('#project-dialog').evaluate(el=>el.open)),'browser Back dismisses project');
 await page.goto(base,{waitUntil:'networkidle'});
 assert(await page.locator('img').evaluateAll(images=>images.every(i=>i.complete&&i.naturalWidth>0)),'every image loads locally');
 assert(await page.locator('.experience-item').count()===3,'experience renders');
 assert(await page.locator('.award-item').count()===3,'awards render');
 assert(await page.locator('.client-wordmark').count()===5,'client wordmarks render');
 assert(await page.locator('#profile-links').isHidden(),'unknown contact details are not displayed');
 for(const width of [320,375,390,600,768,1024,1440]){
  await page.setViewportSize({width,height:900});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  assert(!overflow,`no horizontal overflow at ${width}px`);
 }
 await page.setViewportSize({width:390,height:844});
 await page.goto(base,{waitUntil:'networkidle'});
 await page.screenshot({path:path.join(output,'mobile-full.png'),fullPage:true});
 await page.screenshot({path:path.join(output,'mobile-hero.png')});
 await page.locator('.menu-toggle').click();
 assert(await page.locator('#mobile-nav').isVisible(),'mobile menu opens');
 await page.locator('#mobile-nav a[href="#resume"]').click();
 assert(await page.locator('#mobile-nav').isHidden(),'mobile menu closes after navigation');
 await page.locator('.menu-toggle').click();
 await page.keyboard.press('Escape');
 assert(await page.locator('#mobile-nav').isHidden(),'mobile Escape dismisses navigation');
 await page.locator('[data-project="mimo"]').click();
 await page.screenshot({path:path.join(output,'mobile-project.png')});
 assert(!(await page.locator('#project-dialog').evaluate(el=>el.scrollWidth>el.clientWidth)),'mobile dialog has no horizontal overflow');
 await page.keyboard.press('Escape');
 await page.emulateMedia({reducedMotion:'reduce'});
 assert(await page.locator('.ticker>div').evaluate(el=>getComputedStyle(el).animationName)==='none','reduced motion is respected');
 assert(errors.length===0,'no JavaScript runtime errors');
 assert(failed.length===0,'no failed HTTP requests');
 fs.writeFileSync(path.join(output,'result.json'),JSON.stringify({passed:true,runtimeErrors:errors,httpErrors:failed,viewportWidths:[320,375,390,600,768,1024,1440],date:new Date().toISOString()},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
